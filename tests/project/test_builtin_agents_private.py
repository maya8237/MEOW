"""MEOW's builtin agents are never exposed to Claude Code."""

from meow.project.config import load_config
from meow.project.custom.agent_sync import check_agent_registration, sync_agents


def _sync(project, home):
    custom = load_config(project)["customizations"]
    return sync_agents(custom.catalog, project, home), check_agent_registration(
        custom.catalog, project, home
    )


def test_builtins_are_not_synced(tmp_path):
    project, home = tmp_path / "project", tmp_path / "home"
    (project / ".meow").mkdir(parents=True)

    assert _sync(project, home) == ([], [])
    assert not (project / ".claude" / "agents").exists()


def test_a_retired_claude_table_is_ignored_and_exposes_nothing(tmp_path):
    project, home = tmp_path / "project", tmp_path / "home"
    (project / ".meow").mkdir(parents=True)
    (project / ".meow" / "config.toml").write_text(
        '[claude]\nagents = ["reviewer", "explorer"]\n', encoding="utf-8"
    )

    _sync(project, home)

    assert not (project / ".claude" / "agents" / "meow" / "reviewer.md").exists()


def test_a_copy_an_earlier_version_synced_is_removed(tmp_path):
    project, home = tmp_path / "project", tmp_path / "home"
    (project / ".meow").mkdir(parents=True)
    (project / ".meow" / "config.toml").write_text(
        '[claude]\nagents = ["reviewer"]\n', encoding="utf-8"
    )
    old = project / ".claude" / "agents" / "meow" / "reviewer.md"
    old.parent.mkdir(parents=True)
    old.write_text(
        "---\n# generated by meow; [claude].agents lists reviewer, not this file\n"
        "name: reviewer\ndescription: r\nmeow-managed: project\n---\nReview.\n",
        encoding="utf-8",
    )

    _sync(project, home)

    assert not old.exists()
