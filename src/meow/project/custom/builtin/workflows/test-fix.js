class Stop extends Error {
  constructor(step, message, extra = {}) {
    super(message)
    this.step = step
    this.extra = extra
  }
}

async function ask(label, prompt, schema) {
  const result = await agent(`${RULES}\n\n${prompt}`, schema ? { label, schema } : { label })
  if (result === null) throw new Stop(label, 'agent stopped')
  if (schema && result.error) throw new Stop(label, result.error)
  return result
}

// The expression language of `when` (see MEOW's docs/WORKFLOWS.md).
const TOKEN = /\s*(?:(\d+)|('[^']*'|"[^"]*")|(==|!=|<=|>=|<|>|\(|\))|([A-Za-z_][A-Za-z0-9_-]*(?:\.[A-Za-z_][A-Za-z0-9_-]*)*))/y
const KEYWORDS = ['and', 'or', 'not', 'true', 'false']
const COMPARE = {
  '==': (a, b) => a === b, '!=': (a, b) => a !== b, '<': (a, b) => a < b,
  '<=': (a, b) => a <= b, '>': (a, b) => a > b, '>=': (a, b) => a >= b,
}

function evaluate(source, scope) {
  const tokens = []
  const body = source.trimEnd()
  for (let at = 0; at < body.length; at = TOKEN.lastIndex) {
    TOKEN.lastIndex = at
    const m = TOKEN.exec(body)
    if (!m || TOKEN.lastIndex === at) throw new Error(`unexpected text in ${source}`)
    if (m[1] !== undefined) tokens.push(['literal', Number(m[1])])
    else if (m[2] !== undefined) tokens.push(['literal', m[2].slice(1, -1)])
    else if (m[3] !== undefined) tokens.push(['op', m[3]])
    else tokens.push(KEYWORDS.includes(m[4]) ? [m[4], m[4]] : ['name', m[4]])
  }
  let i = 0
  const take = word => (tokens[i] && tokens[i][1] === word ? (i++, true) : false)
  const atom = () => {
    const token = tokens[i++]
    if (!token) throw new Error(`${source} ends too early`)
    const [kind, value] = token
    if (kind === 'literal') return value
    if (kind === 'true' || kind === 'false') return kind === 'true'
    if (kind === 'name') {
      const [head, ...rest] = value.split('.')
      if (!(head in scope)) throw new Error(`unknown name ${head} in ${source}`)
      let found = scope[head]
      for (const part of rest) found = found && typeof found === 'object' ? found[part] : undefined
      return found === undefined ? null : found
    }
    if (value !== '(') throw new Error(`unexpected ${value} in ${source}`)
    const inner = or()
    if (!take(')')) throw new Error(`missing ) in ${source}`)
    return inner
  }
  const comparison = () => {
    const left = atom()
    const token = tokens[i]
    if (token && token[0] === 'op' && token[1] in COMPARE) {
      i++
      return COMPARE[token[1]](left, atom())
    }
    return left
  }
  const not = () => (take('not') ? !not() : comparison())
  // Like MEOW's evaluator: a chain of `and`/`or` yields a boolean, one operand itself.
  const chain = (word, next, combine) => {
    const values = [next()]
    while (take(word)) values.push(next())
    return values.length === 1 ? values[0] : combine(values.map(Boolean))
  }
  const and = () => chain('and', not, values => values.every(Boolean))
  function or() {
    return chain('or', and, values => values.some(Boolean))
  }
  const result = or()
  if (i < tokens.length) throw new Error(`unexpected ${tokens[i][1]} in ${source}`)
  return result
}

const state = {
  round: 0, feedback: '', steps: {}, gates: {}, delivery: {}, changed: null,
  plan: input.plan || '', run: null, notes: [],
}

function scope() {
  return {
    plan_given: Boolean(input.plan), resume_review: false, review_first: false,
    parallel: false, test: false, bug_mode: false, short_plan: Boolean(MEOW.short_plan),
    checks_configured: Boolean(state.run && state.run.checks_configured),
    inputs: input.inputs || {}, round: state.round, feedback: state.feedback,
    steps: state.steps,
  }
}

const where = () => `--work-dir "${state.run.project_dir}" --active-dir "${state.run.active_dir}"`
const checkpoint = (phase, extra = '') =>
  `\`meow native checkpoint ${phase} --run-id ${state.run.run_id} ${extra}${where()}\``

async function prepare() {
  const flags = [
    input.name ? `--name "${input.name}"` : '--name "<a short slug of the request>"',
    input.noWorktree ? '--no-worktree' : '--fresh',
    input.from ? `--from "${input.from}"` : '',
  ].filter(Boolean).join(' ')
  state.run = await ask('prepare', `Prepare a MEOW run for this request:
<request>
${request || `Implement ${input.plan}`}
</request>
1. In the project root (the current directory; report it as project_dir) run
   \`meow native verify --work-dir .\`; report whether any lint, test or build
   checks are configured as checks_configured.
2. \`meow native prepare ${flags} --work-dir .\`; on a nonzero exit report its message.
3. \`meow native checkpoint preparing --intent run --request "<the request>"
   ${input.target ? `--target "${input.target}" ` : ''}--work-dir <project_dir> --active-dir <active_dir>\`.
Return the JSON fields of prepare and the checkpoint's run_id.`, shape({
    project_dir: text, active_dir: text, plan_file: text, review_file: text,
    docs_dir: text, max_rounds: { type: 'integer' }, use_worktree: flag,
    run_id: text, checks_configured: flag,
  }, ['project_dir', 'active_dir', 'plan_file', 'review_file', 'max_rounds', 'use_worktree', 'run_id']))
  state.plan = state.plan || state.run.plan_file
  log(`Run ${state.run.run_id} in ${state.run.active_dir}`)
}

function gate(step, status, report) {
  const blocks = step.blocks || (state.inLoop ? 'loop' : 'delivery')
  state.steps[step.id] = { status }
  state.gates[step.id] = { status, report, blocks }
  if (blocks === 'delivery') state.delivery[step.id] = status
  if (status !== 'PASS' && (blocks === 'run' || (blocks === 'loop' && !state.inLoop))) {
    throw new Stop(step.id, `gate ${step.id} failed: ${report.slice(0, 500)}`)
  }
  if (status !== 'PASS' && blocks === 'advise') log(`${step.id} (advisory): ${report.slice(0, 300)}`)
}

const verdict = shape({ status: { type: 'string', enum: ['PASS', 'FAIL'] }, report: text }, ['status', 'report'])

async function review(step, role, extra) {
  const brief = await ask(`brief ${step.id}`, `1. ${checkpoint('reviewer_started', `--round ${state.round || 1} `)}
2. \`meow native prompt ${role} ${extra}${where()}\`
Return its system_prompt and query verbatim; review nothing yourself.`,
  shape({ system_prompt: text, query: text }, ['system_prompt', 'query']))
  const prior = state.feedback ? `\n\nThis is a re-review. First resolve each earlier finding as fixed, still failing, or withdrawn:\n<earlier>\n${state.feedback}\n</earlier>` : ''
  const reviewed = await agent(`${brief.system_prompt}\n\n${brief.query}\n\nWork in ${state.run.active_dir}. Write the report to ${state.run.review_file}: \`SUMMARY: ...\`, then \`STATUS: PASS\` or \`STATUS: FAIL\`, then evidence per criterion. Edit no other file.${prior}`, { label: step.id })
  if (reviewed === null) throw new Stop(step.id, 'reviewer stopped')
  const result = await ask(`verdict ${step.id}`, `1. \`meow native verdict "${state.run.review_file}" ${where()}\`: trust it, not a chat summary; a missing or malformed report is FAIL.
2. ${checkpoint('reviewer_finished', `--round ${state.round || 1} --review "${state.run.review_file}" --reviewer <PASS|FAIL> `)}
Return the status and the full report text.`, verdict)
  log(`${step.id}: ${result.status}`)
  gate(step, result.status, result.report)
}

const BUILTIN = {
  async 'builtin.plan'(step) {
    if (state.plan && state.round > 1 && state.feedback) {
      await ask('revise-plan', `Act as MEOW's planner. Revise ${state.plan} to fix this feedback without dropping or widening scope, then ${checkpoint('planned', `--plan "${state.plan}" `)}.
<feedback>
${state.feedback}
</feedback>`, shape({}))
      state.steps[step.id] = { status: 'done' }
      return
    }
    await ask('planner', `Act as MEOW's planner for:
<request>
${request}
</request>
1. \`meow native round "${state.plan}" --reset ${where()}\`, then ${checkpoint('planning')}.
2. \`meow native prompt planner ${where()}\`; follow its instructions and skills.${MEOW.short_plan ? ' Keep the plan short.' : ''}
3. Write ${state.plan}: numbered tasks and a \`## Sprint Contract\` of testable criteria.
4. ${checkpoint('planned', `--plan "${state.plan}" `)}.`, shape({}))
    state.steps[step.id] = { status: 'done' }
  },
  async 'builtin.approve_plan'(step) {
    state.steps[step.id] = { status: 'done' }
    if (input.stopAfterPlan) {
      throw new Stop(step.id, 'awaiting approval', {
        status: 'awaiting_approval', plan_file: state.plan,
        next: `Relaunch with args { request, plan: "${state.plan}" } to continue.`,
      })
    }
  },
  async 'builtin.tasks'(step) {
    state.steps[step.id] = { status: 'skipped' }
    log('Parallel task graphs run only under `meow run`; implementing sequentially.')
  },
  async 'builtin.generate'(step) {
    const role = state.plan ? 'generator' : 'review-fixer'
    const task = state.feedback
      ? `Fix the following, then stop. Verify each finding first; report unsupported or out-of-scope ones instead of acting on them.\n<feedback>\n${state.feedback}\n</feedback>`
      : `Implement the tasks in ${state.plan}.`
    const round = state.round || 1
    const done = await ask(step.id, `Act as MEOW's ${role} in ${state.run.active_dir}.
1. ${checkpoint('generator_started', `--round ${round} `)}
2. \`meow native prompt ${role} ${state.plan ? `--plan "${state.plan}" ` : ''}${where()}\`; follow its instructions, tools and skills.
3. ${task}
4. After every source edit run \`meow native lint --file <path> ${where()}\` and fix what it reports. Do not commit or grade your work.
5. ${checkpoint('generator_finished', `--round ${round} `)} (on an unexpected stop use \`interrupted_mutation\`).`,
    shape({ changed: { type: 'boolean', description: 'Whether any source file was edited.' } }, ['changed']))
    state.changed = done.changed
    state.steps[step.id] = { status: 'done' }
  },
  async 'builtin.verify'(step) {
    const checks = await ask(step.id, `Run MEOW's required checks in ${state.run.active_dir}:
1. \`meow native lint ${where()}\`; fix \`blocking\` findings.
2. \`meow native review-checks --background ${where()}\`, then poll \`meow native review-checks --status ${where()}\` until done. Pending or interrupted checks are infrastructure: rerun them.
Return PASS only when the current required evidence passed, else FAIL with the failing output.`, verdict)
    gate({ ...step, blocks: step.blocks || 'loop' }, checks.status, `Required checks failed:\n${checks.report}`)
  },
  async 'builtin.review'(step) {
    if (state.plan) {
      await review(step, 'reviewer-plan', `--plan "${state.plan}" ${state.run.use_worktree ? '--worktree ' : ''}`)
    } else {
      await review(step, 'reviewer-prompt', `--focus ${JSON.stringify(request)} `)
    }
  },
  async 'builtin.test'(step) {
    throw new Stop(step.id, `the tester runs only under \`meow run\`: use \`meow run --workflow ${meta.name}\``)
  },
  async 'builtin.checks'(step) {
    await BUILTIN['builtin.verify']({ ...step, blocks: step.blocks || 'delivery' })
  },
  async 'builtin.deliver'(step) {
    const blocked = Object.entries(state.delivery).filter(([, status]) => status !== 'PASS')
    if (blocked.length) throw new Stop(step.id, `delivery blocked by ${blocked.map(([id]) => id).join(', ')}`)
    const out = await ask('finalize', `\`meow native finalize ${state.run.run_id} ${where()}\`: it revalidates evidence, commits and pushes a separate worktree's branch. Report \`complete\`; if false, its reason as error. Then read \`meow status ${state.run.run_id} --work-dir "${state.run.project_dir}"\` for the saved MR target. Do not open the MR yourself.`,
    shape({ complete: flag, branch: text, target: text }, ['complete']))
    if (!out.complete) throw new Stop(step.id, 'finalize did not complete')
    state.delivered = out
    state.steps[step.id] = { status: 'done' }
  },
}

async function stage(step) {
  const brief = await ask(`brief ${step.id}`, `\`meow native stage ${step.id} --workflow ${meta.name} --run-id ${state.run.run_id} --round ${state.round || 1} ${state.plan ? `--plan "${state.plan}" ` : ''}${where()}\`
Return its system_prompt, task and report_file verbatim.`,
  shape({ system_prompt: text, task: text, report_file: text }, ['system_prompt', 'task', 'report_file']))
  const feedback = state.feedback ? `\n\nFeedback from the previous round:\n${state.feedback}` : ''
  const reply = await agent(`${brief.system_prompt}\n\n${brief.task}${feedback}\n\nWork in ${state.run.active_dir}.`, { label: step.id })
  if (reply === null) throw new Stop(step.id, 'agent stopped')
  if (!('gate' in step)) {
    state.steps[step.id] = { status: 'done' }
    return
  }
  const result = await ask(`verdict ${step.id}`, `\`meow native verdict "${brief.report_file}" ${where()}\`; a missing or malformed report is FAIL. Return the status and the full report text.`, verdict)
  gate(step, result.status, result.report)
}

async function loop(step) {
  const outer = { round: state.round, gates: state.gates, inLoop: state.inLoop }
  const max = step.max_rounds || state.run.max_rounds
  let previous = null
  for (let round = 1; round <= max; round++) {
    Object.assign(state, { round, gates: {}, changed: null, inLoop: true })
    phase(`${step.id} · round ${round}`)
    await steps(step.loop)
    const failed = Object.values(state.gates).filter(g => g.status !== 'PASS' && g.blocks !== 'advise')
    if (!failed.length) {
      Object.assign(state, outer, { feedback: '' })
      state.steps[step.id] = { status: 'PASS' }
      return
    }
    const signature = failed.map(g => g.report).join('\n\n')
    if (round > 1 && state.changed === false) throw new Stop(step.id, 'stalled: the fix changed no code and the round still failed')
    if (signature === previous) throw new Stop(step.id, 'stalled: two rounds failed the same way')
    previous = signature
    state.feedback = signature
  }
  throw new Stop(step.id, `did not pass within ${max} rounds`, { status: 'exhausted', review_file: state.run.review_file })
}

async function steps(list) {
  for (const step of list) {
    if (step.when && !evaluate(step.when, scope())) {
      state.steps[step.id] = { status: 'skipped' }
      continue
    }
    if ('loop' in step) await loop(step)
    else if ('parallel' in step) await Promise.all(step.parallel.map(child => steps([child])))
    else if ('call' in step || 'sequence' in step) await steps(step.sequence || await callee(step))
    else if ('uses' in step) await BUILTIN[step.uses](step)
    else await stage(step)
  }
}

async function callee(step) {
  const found = await ask(`resolve ${step.call}`, `\`meow native workflow ${step.call} ${where()}\`; return its steps array verbatim as JSON text.`, shape({ steps_json: text }, ['steps_json']))
  return JSON.parse(found.steps_json)
}

try {
  phase('Prepare')
  await prepare()
  await steps(MEOW.steps)
  return { status: 'complete', run_id: state.run.run_id, plan_file: state.plan, review_file: state.run.review_file, ...(state.delivered || {}) }
} catch (error) {
  if (!(error instanceof Stop)) throw error
  log(`Stopped at ${error.step}: ${error.message}`)
  return { status: 'stopped', step: error.step, error: error.message, run_id: state.run && state.run.run_id, ...error.extra }
}
